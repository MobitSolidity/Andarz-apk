#!/usr/bin/env python3
"""Builds the English content documents (D-90) from the Persian ones and the translation table.

    python3 tools/i18n/build_content_en.py

Inputs : spec/andarz_content_fa.json, app/src/main/assets/content_market_fa.json, tools/i18n/fa2en.json
Outputs: app/src/main/assets/content_en.json, app/src/main/assets/content_market_en.json

Every Persian string is replaced by its entry in the table; keys, ids, numbers and structure are kept.
The `csv` block stays Persian on purpose: the CSV files must match the Excel journal's headers whatever the
display language is. Enum `csv` fields stay Persian for the same reason. The script fails when a Persian string
has no translation, so the English documents can never silently fall behind the Persian ones.
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
FA = re.compile('[\u0600-\u06FF]')
table = json.loads((ROOT / 'tools/i18n/fa2en.json').read_text('utf-8'))
missing = []


def tr(node, path=()):
    if isinstance(node, str):
        if not FA.search(node):
            return node
        if path and path[-1] == 'csv':
            return node
        if node in table:
            return table[node]
        missing.append('.'.join(map(str, path)) + ': ' + node[:60])
        return node
    if isinstance(node, list):
        return [tr(v, path + (i,)) for i, v in enumerate(node)]
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if path == () and k == 'csv':
                out[k] = v
            else:
                out[k] = tr(v, path + (k,))
        return out
    return node


base = json.loads((ROOT / 'spec/andarz_content_fa.json').read_text('utf-8'))
market = json.loads((ROOT / 'app/src/main/assets/content_market_fa.json').read_text('utf-8'))
en_base = tr(base)
en_market = tr(market)
for doc in (en_base, en_market):
    doc['meta']['locale'] = 'en'
    doc['meta']['direction'] = 'ltr'
en_base['meta']['translation'] = 'Generated by tools/i18n/build_content_en.py from content_fa.json (D-90). Do not edit by hand.'
en_market['meta']['translation'] = 'Generated by tools/i18n/build_content_en.py from content_market_fa.json (D-90). Do not edit by hand.'
en_base['calendar']['note'] = base['calendar']['note']
key_over = json.loads((ROOT / 'tools/i18n/en_key_overrides.json').read_text('utf-8'))
for k, v in key_over.items():
    if k.startswith('_'):
        continue
    if k not in en_base['ui']:
        missing.append('key override for unknown key ' + k)
    en_base['ui'][k] = v

# Every live-clause literal must still be found in its translated clause text (Clause.render requires it).
for art in en_base['constitution']['articles']:
    for bl in art['blocks']:
        for key in ('refs',):
            text = bl.get('text', '')
            pos = 0
            for r in bl.get(key, []):
                if r['literal'] not in text:
                    missing.append('clause %s: literal "%s" not in text' % (bl.get('id'), r['literal']))
        for it in bl.get('items', []) if isinstance(bl.get('items'), list) else []:
            if isinstance(it, dict):
                for r in it.get('refs', []):
                    if r['literal'] not in it.get('text', ''):
                        missing.append('item %s: literal "%s" not in text' % (it.get('id'), r['literal']))

if missing:
    sys.stderr.write('untranslated or broken:\n  ' + '\n  '.join(missing) + '\n')
    sys.exit(1)

out = ROOT / 'app/src/main/assets'
(out / 'content_en.json').write_text(json.dumps(en_base, ensure_ascii=False, indent=1) + '\n', 'utf-8')
(out / 'content_market_en.json').write_text(json.dumps(en_market, ensure_ascii=False, indent=1) + '\n', 'utf-8')
print('wrote content_en.json and content_market_en.json')
